#!/bin/sh
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPO=$(CDPATH= cd -- "$ROOT/../.." && pwd)
# Standalone checkout: npm ci supplies the compiler; TSC may override its path.
TSC=${TSC:-"$REPO/node_modules/typescript/bin/tsc"}
[ -f "$TSC" ] || { echo "Run npm ci, or set TSC to an installed TypeScript compiler" >&2; exit 1; }
OUT=${1:-"$ROOT/klaus-audio-proof.zip"}
case "$OUT" in /*) ;; *) OUT="$PWD/$OUT" ;; esac

# A credential-bearing package must stay outside every checkout of this repo.
COMMON=$(git -C "$REPO" rev-parse --path-format=absolute --git-common-dir)
MAIN_REPO=$(CDPATH= cd -- "$(dirname "$COMMON")" && pwd -P)
REAL_REPO=$(CDPATH= cd -- "$REPO" && pwd -P)
REAL_OUT=$(CDPATH= cd -- "$(dirname "$OUT")" && pwd -P)
if [ -n "${NOKIA_BRIDGE_URL:-}" ]; then
  for SOURCE_ROOT in "$REAL_REPO" "$MAIN_REPO"; do
    case "$REAL_OUT" in
      "$SOURCE_ROOT"|"$SOURCE_ROOT"/*)
        echo 'Live credential packages must be written outside the repository.' >&2
        exit 1 ;;
    esac
  done
fi

node "$TSC" --strict --ignoreDeprecations 6.0 --target ES5 --lib DOM,ES2015,ES2016 --skipLibCheck --outFile "$ROOT/app.js" "$ROOT/keys.ts" "$ROOT/storage.ts" "$ROOT/api.ts" "$ROOT/tts.ts" "$ROOT/ui.ts" "$ROOT/app.ts"
node -e 'JSON.parse(require("fs").readFileSync(process.argv[1], "utf8"))' "$ROOT/manifest.webapp"
command -v zip >/dev/null 2>&1 || { echo "zip is required" >&2; exit 1; }

# H6: tempdir with private permissions so credential files are never world-readable
OLDUMASK=$(umask)
umask 077
TMP=$(mktemp -d)
umask "$OLDUMASK"
trap 'rm -rf "$TMP"' EXIT HUP INT TERM

# H6: always include a blank config.js template so the app loads offline without a 404.
# For live builds, overwrite it using JSON.stringify to safely escape URL and token.
BLANK_CONFIG="$TMP/config.js"
cat > "$BLANK_CONFIG" << 'ENDCFG'
// Runtime bridge configuration — blank template (offline mode).
// This file is generated by build.sh with NOKIA_BRIDGE_URL; never commit credentials.
var NOKIA_RUNTIME_CONFIG = {
  bridgeUrl: "",
  bridgeToken: ""
};
ENDCFG
chmod 600 "$BLANK_CONFIG"

# Build a live config.js only when NOKIA_BRIDGE_URL is set; never commit the token.
if [ -n "${NOKIA_BRIDGE_URL:-}" ]; then
  # Read the private file within Node; never place the bearer in argv or stdout.
  node -e '
    const fs = require("fs");
    const file = process.env.NOKIA_CONFIG_FILE;
    if (!file || (fs.statSync(file).mode & 0o077)) throw new Error("NOKIA_CONFIG_FILE must be private (0600)");
    const config = JSON.parse(fs.readFileSync(file, "utf8"));
    const token = config.bridgeToken || config.token;
    const url = process.env.NOKIA_BRIDGE_URL;
    if (typeof token !== "string" || !/^[A-Za-z0-9_-]{32,128}$/.test(token)) throw new Error("Invalid device token");
    const parsed = new URL(url);
    if (parsed.protocol !== "https:" || parsed.username || parsed.password || parsed.search || parsed.hash) throw new Error("Bridge URL must be HTTPS without credentials or query");
    const runtime = {bridgeUrl: url.replace(/\/$/, ""), bridgeToken: token};
    const timeout = process.env.NOKIA_POLL_TIMEOUT_MS;
    if (timeout) {
      if (!/^[0-9]{4,7}$/.test(timeout)) throw new Error("NOKIA_POLL_TIMEOUT_MS must be milliseconds (1000-9999999)");
      runtime.pollTimeoutMs = Number(timeout);
    }
    fs.writeFileSync(process.argv[1], "var NOKIA_RUNTIME_CONFIG = " + JSON.stringify(runtime) + ";\n", {mode: 0o600});
  ' "$BLANK_CONFIG"
  (cd "$ROOT" && zip -q -j "$TMP/package.zip" manifest.webapp index.html style.css app.js "$BLANK_CONFIG")
else
  echo 'NOKIA_BRIDGE_URL not set — building offline-only package (blank config.js included)' >&2
  (cd "$ROOT" && zip -q -j "$TMP/package.zip" manifest.webapp index.html style.css app.js "$BLANK_CONFIG")
fi
chmod 600 "$TMP/package.zip"
mv "$TMP/package.zip" "$OUT"
echo "Built $OUT"
